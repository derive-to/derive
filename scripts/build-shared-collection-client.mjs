import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
export const OUT = join(ROOT, "packages/core/src/shared-collection-client.gen.ts")

export async function generateSharedCollectionClient() {
  const result = await build({
    entryPoints: [join(ROOT, "packages/core/src/shared-collection-client.ts")],
    bundle: true,
    format: "iife",
    globalName: "__deriveCollections",
    target: "es2023",
    platform: "browser",
    minify: true,
    legalComments: "none",
    write: false,
  })
  const banner =
    "// @generated by scripts/build-shared-collection-client.mjs — DO NOT EDIT.\n" +
    "// Edit shared-collection-client.ts, then run `pnpm build:shared-client`.\n"
  return (
    banner +
    "\nexport const SHARED_COLLECTION_CLIENT_JS = " +
    JSON.stringify(result.outputFiles[0].text.trim()) +
    "\n"
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, await generateSharedCollectionClient())
}
