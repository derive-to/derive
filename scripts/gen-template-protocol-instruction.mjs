#!/usr/bin/env node
// Generates the protocol/fact preservation instruction into the server and browser
// runtimes from one source. The web client cannot import @derive/core at runtime (the
// HTTP-client boundary is a CI invariant), so checked-in generation keeps the user-facing
// handoff DRY without weakening that architecture.
//
//   node scripts/gen-template-protocol-instruction.mjs
//   node scripts/gen-template-protocol-instruction.mjs --check
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const SOURCE = join(ROOT, "packages/core/src/template-protocol-instruction.txt")
const TARGETS = [
  join(ROOT, "packages/core/src/template-protocol-instruction.gen.ts"),
  join(ROOT, "apps/web/src/pages/templates/template-protocol-instruction.gen.ts"),
]
const instruction = readFileSync(SOURCE, "utf8").trim()
const generated =
  "// GENERATED by scripts/gen-template-protocol-instruction.mjs — do not edit.\n" +
  "// Regenerate: pnpm gen:template-protocol-instruction\n\n" +
  "/** The shared preservation contract for every ordinary artifact-template handoff. */\n" +
  `export const TEMPLATE_PROTOCOL_INSTRUCTION = ${JSON.stringify(instruction)}\n`

const check = process.argv.includes("--check")
const stale = []
for (const target of TARGETS) {
  if (check) {
    let current = ""
    try {
      current = readFileSync(target, "utf8")
    } catch {
      // Missing output is stale.
    }
    if (current !== generated) stale.push(target.slice(ROOT.length + 1))
  } else {
    writeFileSync(target, generated)
  }
}

if (check && stale.length) {
  console.error("template-protocol-instruction: generated files are stale:")
  for (const target of stale) console.error(`  - ${target}`)
  console.error("  Fix: pnpm gen:template-protocol-instruction")
  process.exit(1)
}

if (check) console.log("template-protocol-instruction: ok — server and browser handoffs match")
else console.log(`template-protocol-instruction: wrote ${TARGETS.length} generated modules`)
