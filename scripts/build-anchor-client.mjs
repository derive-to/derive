// Bundles the in-iframe comment-anchor client (packages/core/src/anchor-client.ts and
// its imports from anchor-shared) into a single self-executing IIFE string, emitted as
// a committed TS module (anchor-client.gen.ts) that the API serves at
// /raw/derive-client.js. Committing the generated output means the runtime (node+tsx and
// the Workers build) imports a plain string constant — esbuild is a dev/CI-only tool,
// never in the serving path. `pnpm build:anchor-client` regenerates it; CI's
// check-anchor-client asserts it's in sync (the deterministic-gate pattern).

import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const ENTRY = join(ROOT, "packages/core/src/anchor-client.ts")
export const OUT = join(ROOT, "packages/core/src/anchor-client.gen.ts")

// Produce the exact text of the generated module. Pure (no writes) so the CI check can
// compare it against the committed file without a temp path.
export async function generateAnchorClient() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true, // inline the anchor-shared imports so the client is self-contained
    format: "iife", // a self-executing block; the client only registers listeners
    target: "es2019", // the sandboxed iframe runs in modern browsers
    platform: "browser",
    minify: true, // it's generated + served on every artifact view — ship it small
    legalComments: "none",
    write: false,
  })
  const js = result.outputFiles[0].text.trim()
  const banner =
    "// @generated by scripts/build-anchor-client.mjs — DO NOT EDIT.\n" +
    "// Edit packages/core/src/anchor-client.ts (+ anchor-shared.ts), then run\n" +
    "// `pnpm build:anchor-client`. CI's check-anchor-client asserts this is in sync.\n"
  // biome-ignore lint/style/useTemplate: explicit concatenation reads clearer here.
  return banner + "\nexport const ANCHOR_CLIENT_JS = " + JSON.stringify(js) + "\n"
}

// CLI: write the file.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const content = await generateAnchorClient()
  writeFileSync(OUT, content)
  const bytes = new TextEncoder().encode(content).length
  console.log(`anchor-client: wrote ${OUT} (${bytes} bytes)`)
}
