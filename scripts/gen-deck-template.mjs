#!/usr/bin/env node
// Generates the deck starter into every surface that scaffolds one, from ONE source:
// packages/core/src/deck-template.html.
//
// Three surfaces hand a person or an agent a starting deck — the MCP template resource
// (derive://decks/template), `derive init --template slides`, and the library's "Start a
// deck" — and they must hand over the SAME deck, because the decks skill documents one
// pattern. They can't share a module: the CLI is deliberately standalone (no @derive/core)
// and the web client never pulls core into its bundle. So the canonical deck is a real
// .html file (editable and previewable as what it is, like the skills are real .md files)
// and this script inlines it into a committed module per surface — the deterministic-gate
// pattern, same as scripts/build-anchor-client.mjs.
//
//   node scripts/gen-deck-template.mjs           # write the generated modules
//   node scripts/gen-deck-template.mjs --check   # fail if any is stale (CI)
//
// It also GUARDS the source: the four structural pieces below are what make the file a
// deck rather than a styled page, and every one of them is silent when removed (the page
// still publishes, still renders, and simply never lights up the deck bar). Checking them
// here means an edit that breaks the pattern fails the build instead of shipping.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const SRC = join(ROOT, "packages/core/src/deck-template.html")

// The title the starter names itself with, swapped by deckTemplate(title). It appears in
// <title>, the opening eyebrow, and the <h1> — all three are the deck naming itself.
const TITLE_SENTINEL = "New deck"

/** The load-bearing contract. Each entry: what to find, and what breaks without it. */
const CONTRACT = [
  ['source: "derive-deck"', "the state post — without it the host never treats this as a deck"],
  ['"derive-host"', "the host-command listener — without it the deck bar can't drive the deck"],
  ['data-derive-slide="0"', "stable slide identity — without it comments drift between slides"],
  ["width: 1280px", "the fixed stage width"],
  ["height: 720px", "the fixed stage height"],
]

const html = readFileSync(SRC, "utf8")

const problems = []
for (const [needle, why] of CONTRACT)
  if (!html.includes(needle)) problems.push(`missing ${needle} — ${why}`)
// The same count the runtime uses (packages/core/src/decks.ts): real slide tags only, and
// HTML comments stripped first — this file's own annotated header describes a slide element
// in prose, and prose about decks must never count as one.
const slideCount = (
  html
    .replace(/<!--[\s\S]*?-->/g, "")
    .match(
      /<(?:section|div|article|li)\b[^>]*(?:class\s*=\s*["'][^"']*\bslide\b|data-derive-slide\s*=)/gi,
    ) ?? []
).length
if (slideCount < 2) problems.push(`only ${slideCount} slide section(s) — a deck needs at least 2`)
const titleCount = html.split(TITLE_SENTINEL).length - 1
if (titleCount < 2)
  problems.push(
    `the title sentinel ${JSON.stringify(TITLE_SENTINEL)} appears ${titleCount}x — deckTemplate(title) needs it in <title> and the heading`,
  )
if (problems.length) {
  console.error("gen-deck-template: packages/core/src/deck-template.html is not a valid deck:")
  for (const p of problems) console.error(`  - ${p}`)
  process.exit(1)
}

const BANNER = (lang) =>
  `// GENERATED by scripts/gen-deck-template.mjs from packages/core/src/deck-template.html — do not edit.\n` +
  `// Regenerate: pnpm gen:deck-template${lang === "js" ? "" : ""}\n` +
  `//\n` +
  `// The canonical Derive deck: a fixed 1280x720 stage, slides that layer and crossfade, and\n` +
  `// the derive-deck protocol that turns on the host's deck bar, Present mode, and\n` +
  `// slide-pinned comments. Documented for agents in derive://skills/decks. A pure leaf: no\n` +
  `// imports, safe in every build.\n`

const DOC =
  `/** The canonical deck starter, with its own title. Pass the deck's title to name it. */`

/** The generated module text for a target. `lang` is "ts" or "js". */
const moduleFor = (lang) => {
  const typed = lang === "ts"
  return (
    `${BANNER(lang)}\nexport const DECK_TEMPLATE${typed ? ": string" : ""} = ${JSON.stringify(html)}\n\n` +
    `${DOC}\nexport const deckTemplate = (title${typed ? ": string" : ""})${typed ? ": string" : ""} =>\n` +
    `  DECK_TEMPLATE.replaceAll(${JSON.stringify(TITLE_SENTINEL)}, title)\n`
  )
}

// One target per surface that hands over a starting deck. The CLI gets plain JS (it ships
// as source and depends on nothing); core serves the MCP resource; web prefills the editor.
const TARGETS = [
  { path: join(ROOT, "packages/core/src/deck-template.gen.ts"), lang: "ts" },
  { path: join(ROOT, "apps/web/src/lib/deck-template.gen.ts"), lang: "ts" },
  { path: join(ROOT, "packages/cli/src/deck-template.gen.js"), lang: "js" },
]

const check = process.argv.slice(2).includes("--check")
const stale = []
for (const { path, lang } of TARGETS) {
  const want = moduleFor(lang)
  if (check) {
    let have = ""
    try {
      have = readFileSync(path, "utf8")
    } catch {
      /* missing → stale */
    }
    if (have !== want) stale.push(path.slice(ROOT.length + 1))
  } else {
    writeFileSync(path, want)
  }
}

if (check) {
  if (stale.length) {
    console.error("check-deck-template: stale vs packages/core/src/deck-template.html:")
    for (const p of stale) console.error(`  - ${p}`)
    console.error("  Fix: pnpm gen:deck-template")
    process.exit(1)
  }
  console.log("check-deck-template: ok — every surface serves the same canonical deck")
} else {
  const kb = Math.round(new TextEncoder().encode(html).length / 102.4) / 10
  console.log(
    `gen-deck-template: wrote ${TARGETS.length} modules from deck-template.html (${kb}KB, ${slideCount} slides)`,
  )
}
