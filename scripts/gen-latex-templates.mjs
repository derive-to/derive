#!/usr/bin/env node
// Generates the paper starters into every surface that scaffolds one, from ONE source per
// template: packages/core/src/latex-templates/<id>/ (main.tex and the .bib), plus
// packages/core/src/latex-templates/derive.sty, the package the export ships, which is also
// mirrored into core as derive-sty.gen.ts so the export and a scaffolded project hold the
// same bytes.
//
// Three runtime surfaces hand a person or an agent a starting paper: the API's template
// route (the web's New page, the MCP resource) and `derive init --template siggraph|cvpr`.
// The CLI is deliberately standalone (no @derive/core), so this script inlines the files
// into each runtime package, exactly as gen-deck-template.mjs does for the deck.
//
//   node scripts/gen-latex-templates.mjs           # write the generated modules
//   node scripts/gen-latex-templates.mjs --check   # fail if any is stale (CI)
//
// It also GUARDS each source: the pieces below are what make the file a paper Derive can
// render and export (the dynamic bindings, the bibliography, the class), and each is silent
// when removed. Checking them here means an edit that breaks the pattern fails the build.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const SRC = join(ROOT, "packages/core/src/latex-templates")
const DERIVE_STY = readFileSync(join(SRC, "derive.sty"), "utf8")
const problems = []

/** The templates, in the order surfaces list them. `bib` is what `\bibliography{}` names. */
const TEMPLATES = [
  {
    id: "acm-siggraph",
    label: "ACM SIGGRAPH",
    description:
      "acmart in the sigconf format with author-year citations, a dynamic teaser figure and a dynamic results table. Switch to acmtog for the journal track.",
    bib: "references",
    contract: [
      ["\\documentclass[sigconf]{acmart}", "the SIGGRAPH conference class"],
      ["\\citestyle{acmauthoryear}", "SIGGRAPH requires author-year citations"],
      ["\\bibliographystyle{ACM-Reference-Format}", "the ACM reference style"],
    ],
  },
  {
    id: "cvpr",
    label: "CVPR",
    description:
      "The CVPR author kit's article layout in review mode, numeric citations, a dynamic teaser figure and a dynamic results table. The kit's style files are fetched when the paper is created.",
    bib: "main",
    contract: [
      ["\\usepackage[review]{cvpr}", "the author kit's review mode"],
      ["\\bibliographystyle{ieeenat_fullname}", "the kit's reference style"],
      ["\\def\\paperID{", "the paper id the review band prints"],
    ],
  },
]

/** Every template must carry these; each is silent when removed. A needle is a string or,
 *  for a macro that takes options, a pattern. */
const SHARED_CONTRACT = [
  ["\\usepackage{derive}", "loads derive.sty; without it \\derivetable is undefined in TeX"],
  ["\\begin{document}", "a compilable document"],
  ["\\maketitle", "the title block the renderer and the class both typeset here"],
  [
    /\\derivetable(?:\[[^\]]*\])?\{results\}/,
    "the dynamic results table the docs and skill describe",
  ],
  [
    /\\derivefigure(?:\[[^\]]*\])?\{teaser\}/,
    "the dynamic teaser figure the docs and skill describe",
  ],
  ["\\end{document}", "a compilable document"],
]
const has = (text, needle) =>
  typeof needle === "string" ? text.includes(needle) : needle.test(text)

if (!/\\ProvidesPackage\{derive\}/.test(DERIVE_STY) || !DERIVE_STY.includes("\\derivetable"))
  problems.push("derive.sty: must provide the derive package with \\derivetable and \\derivefigure")

const readTemplate = (t) => {
  const dir = join(SRC, t.id)
  if (!existsSync(dir)) throw new Error(`missing template folder ${dir}`)
  const files = {}
  for (const name of readdirSync(dir).sort()) files[name] = readFileSync(join(dir, name), "utf8")
  files["derive.sty"] = DERIVE_STY
  return files
}

const generated = TEMPLATES.map((t) => {
  const files = readTemplate(t)
  const main = files["main.tex"]
  if (!main) {
    problems.push(`${t.id}: no main.tex`)
    return { ...t, files }
  }
  for (const [needle, why] of [...SHARED_CONTRACT, ...t.contract])
    if (!has(main, needle)) problems.push(`${t.id}/main.tex: missing ${needle} — ${why}`)
  if (!main.includes(`\\bibliography{${t.bib}}`))
    problems.push(`${t.id}/main.tex: must cite \\bibliography{${t.bib}}`)
  if (!files[`${t.bib}.bib`]) problems.push(`${t.id}: missing ${t.bib}.bib`)
  return { ...t, files }
})
if (problems.length) {
  console.error("gen-latex-templates: a template source is not a valid paper:")
  for (const p of problems) console.error(`  - ${p}`)
  process.exit(1)
}

const BANNER =
  `// GENERATED by scripts/gen-latex-templates.mjs from packages/core/src/latex-templates/ — do not edit.\n` +
  `// Regenerate: pnpm gen:latex-templates\n` +
  `//\n` +
  `// The paper starters (ACM SIGGRAPH, CVPR): main.tex, its .bib and derive.sty, as a\n` +
  `// path -> text map a bundle publish takes as-is. Documented for agents in\n` +
  `// derive://skills/latex. A pure leaf: no imports, safe in every build.\n`

const entryFor = (t) => ({
  id: t.id,
  label: t.label,
  description: t.description,
  entry: "main.tex",
  files: t.files,
})

/** The generated module text for a target. `lang` is "ts" or "js". */
const moduleFor = (lang) => {
  const typed = lang === "ts"
  const ids = generated.map((t) => JSON.stringify(t.id)).join(" | ")
  const typeDecl = typed
    ? `export type LatexTemplateId = ${ids}\n\n` +
      `export interface LatexTemplateFiles {\n  id: LatexTemplateId\n  label: string\n  description: string\n  /** The bundle entry, the page Derive renders. */\n  entry: "main.tex"\n  /** Every file of the starter by path (text only; the starters need no binary). */\n  files: Record<string, string>\n}\n\n`
    : ""
  const value = JSON.stringify(
    Object.fromEntries(generated.map((t) => [t.id, entryFor(t)])),
    null,
    2,
  )
  return (
    `${BANNER}\n${typeDecl}` +
    `export const LATEX_TEMPLATES${typed ? ": Record<LatexTemplateId, LatexTemplateFiles>" : ""} = ${value}\n`
  )
}

const STY_BANNER =
  `// GENERATED by scripts/gen-latex-templates.mjs from packages/core/src/latex-templates/derive.sty — do not edit.\n` +
  `// Regenerate: pnpm gen:latex-templates\n` +
  `//\n` +
  `// derive.sty: the LaTeX package behind \\derivetable and \\derivefigure, written into every\n` +
  `// source export and every paper starter. A pure leaf: no imports, safe in every build.\n`
const styModule = () =>
  `${STY_BANNER}\nexport const DERIVE_STY: string = ${JSON.stringify(DERIVE_STY)}\n`

const TARGETS = [
  { path: join(ROOT, "packages/core/src/latex-templates.gen.ts"), lang: "ts" },
  { path: join(ROOT, "packages/cli/src/latex-templates.gen.js"), lang: "js" },
  { path: join(ROOT, "packages/core/src/derive-sty.gen.ts"), lang: "sty" },
]

const check = process.argv.slice(2).includes("--check")
const stale = []
for (const { path, lang } of TARGETS) {
  const next = lang === "sty" ? styModule() : moduleFor(lang)
  const current = existsSync(path) ? readFileSync(path, "utf8") : null
  if (current === next) continue
  if (check) stale.push(path)
  else writeFileSync(path, next)
}
if (check && stale.length) {
  console.error("gen-latex-templates: generated modules are stale; run pnpm gen:latex-templates:")
  for (const p of stale) console.error(`  - ${p}`)
  process.exit(1)
}
console.log(
  check
    ? "check-latex-templates: ok — the generated modules match the template sources"
    : `gen-latex-templates: wrote ${TARGETS.length} modules (${generated.map((t) => t.id).join(", ")})`,
)
